"""Explore BM25 vs TF-IDF on AI-provisionally judged development pools.

Not an independent test, model-selection benchmark, or evidence of generalization.
Pool generated by candidate retrieval and labels provided by AI. Never reads holdout.
"""
from __future__ import annotations
from pathlib import Path
import collections, csv, json, math, statistics

ROOT=Path(__file__).resolve().parents[1]
LABELS=ROOT/'data/research/relevance_dev_expanded_PRIVATE.csv'
RUNS=ROOT/'data/research/retrieval_dev_runs_PRIVATE.csv'
OUT=ROOT/'reports/experiments/relevance_dev_ai_completion_seed31'


def read(path):
    with path.open(encoding='utf-8-sig',newline='') as f:
        return list(csv.DictReader(f))


def dcg(grades):
    return sum((2**g-1)/math.log2(i+2) for i,g in enumerate(grades))


def main():
    if not LABELS.is_file() or not RUNS.is_file():
        raise SystemExit(f'Missing local labels or retrieval runs: {LABELS}, {RUNS}')
    labels=read(LABELS)
    runs=read(RUNS)
    qrels={}
    for row in labels:
        key=(row['question_id'],row['paper_id'])
        if key in qrels:raise ValueError(f'Duplicate question/paper {key}')
        g=str(row['relevance_grade']).strip()
        if g not in ('','?','0','1','2'):
            raise ValueError(f'Invalid grade {g!r} for {key}')
        qrels[key]=int(g) if g in ('0','1','2') else None
    pending=sum(v is None for v in qrels.values())
    grouped=collections.defaultdict(list)
    for row in runs:grouped[(row['question_id'],row['method'])].append(row)
    questions=sorted({row['question_id'] for row in runs})
    methods=sorted({row['method'] for row in runs})
    expected={'BM25','TFIDF'}
    if set(methods)!=expected:raise ValueError(f'Expected BM25 and TFIDF runs; got {methods}')
    results=[]; excluded=[]
    for q in questions:
        # A *complete* judged top-10 for both methods, including 0 labels, is mandatory.
        retrieved={}
        for method in methods:
            rows=sorted(grouped[q,method],key=lambda r:int(r['rank']))
            if len(rows)!=10 or [int(r['rank']) for r in rows]!=list(range(1,11)):
                raise ValueError(f'Expected ranks 1..10 for {q}/{method}')
            retrieved[method]=[qrels.get((q,r['paper_id'])) for r in rows]
        if any(v is None for g in retrieved.values() for v in g):
            excluded.append(q)
            continue
        # IDCG uses all graded documents for the query in the pooled assessment set.
        corpus_grades=[v for (qid,_),v in qrels.items() if qid==q and v is not None]
        best=sorted(corpus_grades,reverse=True)[:10]
        idcg=dcg(best)
        if idcg==0:
            excluded.append(q)
            continue
        for method in methods:
            grades=retrieved[method]
            ndcg=dcg(grades)/idcg
            p10=sum(g>0 for g in grades)/10
            mrr=next((1/(i+1) for i,g in enumerate(grades) if g>0),0)
            results.append({'question_id':q,'method':method,'nDCG@10_pooled':round(ndcg,5),
              'Precision@10_AI':round(p10,5),'MRR@10_AI':round(mrr,5),'pool_positive_count':sum(g>0 for g in corpus_grades)})
    OUT.mkdir(parents=True,exist_ok=True)
    fields=['question_id','method','nDCG@10_pooled','Precision@10_AI','MRR@10_AI','pool_positive_count']
    with (OUT/'per_question_exploratory.csv').open('w',encoding='utf-8',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(results)
    summary={m:{metric:round(statistics.mean(float(r[metric]) for r in results if r['method']==m),5) if any(r['method']==m for r in results) else None for metric in fields[2:5]} for m in methods}
    report={'label_source':'provisional AI grades (NOT independent ground truth)','evaluation_scope':'development-only, retriever-pooled judged candidates','method_note':'BM25/TFIDF only; no dense or cross-encoder rankings were supplied for the new collection.', 'n_dev_question_pairs':len(qrels),'n_ungraded_or_uncertain':pending,'scored_questions':len({r['question_id'] for r in results}), 'excluded_questions':excluded, 'quality':summary, 'caveats':['Pooled candidates were collected by retrieval; reported scores are selection-biased.','Labels were generated using the supplied abstracts, without independent human validation.','Ten questions are too few for a robust multi-domain generalization claim.','One uncertain record is excluded with its entire question for a fair paired comparison.','No model hyperparameters should be chosen from these scores as though they were an independent benchmark.']}
    (OUT/'exploratory_summary.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print('Exploratory comparisons; NOT independently validated accuracy results')
    print(f"Scored {report['scored_questions']} development questions; excluded {', '.join(excluded) or 'none'}")
    for m in methods:print(m,summary[m])
    print('Report:',OUT/'exploratory_summary.json')
    print('Rows:',OUT/'per_question_exploratory.csv')
    # Optional figure: visualizes exploratory development scores only.
    try:
        import matplotlib.pyplot as plt
        names=['Pooled nDCG@10','Precision@10','MRR@10']
        metrics=['nDCG@10_pooled','Precision@10_AI','MRR@10_AI']
        fig,ax=plt.subplots(figsize=(6.4,3.2))
        ax.bar([i-.18 for i in range(3)],[summary['BM25'][k] for k in metrics],width=.36,label='BM25')
        ax.bar([i+.18 for i in range(3)],[summary['TFIDF'][k] for k in metrics],width=.36,label='TF-IDF')
        ax.set_ylim(0,1.08);ax.set_xticks([0,1,2],names)
        ax.set_ylabel('Provisional development metric')
        ax.set_title('AI-judged retrieval diagnostics (not test accuracy)')
        ax.legend(frameon=False); fig.tight_layout()
        fig_dir=ROOT/'reports/figures'
        fig_dir.mkdir(parents=True,exist_ok=True)
        image=fig_dir/'09_provisional_ai_dev_retrieval.png'
        fig.savefig(image,dpi=145);plt.close(fig)
        print('Figure:',image)
    except ImportError:
        print('Matplotlib unavailable; JSON and CSV saved without chart.')


if __name__=='__main__':main()
